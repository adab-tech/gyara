def fuzz(n: int, seed: int) -> list:
    rng = random.Random(seed)
    alphabet = list("abdkyBDKYstTSaeiou  '’ʼ.,!?0123456789/()%$₦@*\n_") + list("ɓɗƙƴƁ")
    return ["".join(rng.choice(alphabet) for _ in range(rng.randint(0, 24))) for _ in range(n)]


def build() -> dict:
    texts = HAND + fuzz(300, seed=20261015)
    syll_words = WORDS + [t for t in fuzz(120, seed=7) if t]
    return {
        "_about": "Generated by scripts/gen_vectors.py from the Python implementation. Do not edit by hand.",
        "normalize": [{"in": t, "out": normalize(t)} for t in texts],
        "normalize_keep_digits": [{"in": t, "out": normalize(t, digits=False)} for t in texts],
        "cardinal": [{"in": n, "out": hausa_cardinal(n)} for n in INTS],
        "spell": [{"in": t, "out": spell_out_numbers(t)} for t in texts if t.isascii()],
        "glosses": [{"in": t, "out": strip_english_glosses(t)} for t in texts],
        "speech": [{"in": t, "out": prepare_for_speech(t)} for t in texts],
        "speech_keep_glosses": [
            {"in": t, "out": prepare_for_speech(t, strip_glosses=False)} for t in texts
        ],
        "syllables": [
            {"in": w, "out": [[s.text, s.weight] for s in syllabify(w)]} for w in syll_words
        ],
        "tone": [{"in": t, "out": annotate_tones(t)} for t in texts],
        "tone_guess": [{"in": t, "out": annotate_tones(t, guess=True)} for t in texts],
        "audit": [{"in": t, "out": audit_text(t).to_dict()} for t in texts],
        "stats": [{"in": CORPUS, "out": dataset_stats(CORPUS)}],
        "lexicon": LEXICON,
    }


def main() -> int:
    text = json.dumps(build(), ensure_ascii=False, indent=1, sort_keys=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("tests/vectors.json is stale: run `python scripts/gen_vectors.py`")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
